/**
 * Report Manager - Single canonical latest report
 * 
 * Replaces the accumulating dated reports with a single LATEST.md file.
 * Preserves durable project knowledge in appropriate context files.
 */

import { readFile, writeFile, mkdir, unlink } from 'fs/promises';
import { existsSync } from 'fs';
import { resolve, dirname } from 'path';

export interface TaskReport {
  taskId: string;
  timestamp: string;
  classification: 'T1' | 'T2' | 'T3';
  objective: string;
  affectedFiles: string[];
  changesSummary: string;
  verificationResults: {
    typecheck: boolean;
    tests: boolean;
    i18n: boolean;
    gitDiffCheck: boolean;
  };
  qaStatus: 'PASS' | 'FAIL' | 'BLOCKED' | 'NOT_RUN';
  qaDetails?: string;
  gitCommit?: string;
  status: 'COMPLETED' | 'PARTIAL' | 'BLOCKED';
  notes?: string;
}

const REPORT_DIR = '.ai/reports';
const LATEST_REPORT = `${REPORT_DIR}/LATEST.md`;

async function ensureReportDir(): Promise<void> {
  try {
    await mkdir(REPORT_DIR, { recursive: true });
  } catch (e) {
    // Directory might already exist
  }
}

function formatReport(report: TaskReport): string {
  const lines: string[] = [];
  
  lines.push(`# AI Office Task Report — ${report.taskId}`);
  lines.push('');
  lines.push(`**Timestamp:** ${report.timestamp}`);
  lines.push(`**Classification:** ${report.classification}`);
  lines.push(`**Objective:** ${report.objective}`);
  lines.push(`**Status:** ${report.status}`);
  lines.push(`**Git Commit:** ${report.gitCommit || 'Not committed'}`);
  lines.push('');
  
  lines.push('## Affected Files');
  if (report.affectedFiles.length > 0) {
    report.affectedFiles.forEach(f => lines.push(`- \`${f}\``));
  } else {
    lines.push('- None');
  }
  lines.push('');
  
  lines.push('## Changes Summary');
  lines.push(report.changesSummary);
  lines.push('');
  
  lines.push('## Verification Results');
  lines.push(`- Typecheck: ${report.verificationResults.typecheck ? '✅ PASS' : '❌ FAIL'}`);
  lines.push(`- Tests: ${report.verificationResults.tests ? '✅ PASS' : '❌ FAIL'}`);
  lines.push(`- I18n Parity: ${report.verificationResults.i18n ? '✅ PASS' : '❌ FAIL'}`);
  lines.push(`- Git Diff Check: ${report.verificationResults.gitDiffCheck ? '✅ PASS' : '❌ FAIL'}`);
  lines.push('');
  
  lines.push('## QA Status');
  lines.push(`**${report.qaStatus}**`);
  if (report.qaDetails) {
    lines.push('');
    lines.push(report.qaDetails);
  }
  lines.push('');
  
  if (report.notes) {
    lines.push('## Notes');
    lines.push(report.notes);
    lines.push('');
  }
  
  lines.push('---');
  lines.push(`*Report generated by AI Office at ${report.timestamp}*`);
  
  return lines.join('\n');
}

export async function writeLatestReport(report: TaskReport): Promise<void> {
  await ensureReportDir();
  const content = formatReport(report);
  await writeFile(LATEST_REPORT, content, 'utf-8');
}

export async function readLatestReport(): Promise<string | null> {
  try {
    return await readFile(LATEST_REPORT, 'utf-8');
  } catch {
    return null;
  }
}

export async function getLatestReportSummary(): Promise<{ exists: boolean; timestamp?: string; taskId?: string }> {
  const content = await readLatestReport();
  if (!content) {
    return { exists: false };
  }
  
  const timestampMatch = content.match(/\*\*Timestamp:\*\* (.+)/);
  const taskIdMatch = content.match(/# AI Office Task Report — (.+)/);
  
  return {
    exists: true,
    timestamp: timestampMatch?.[1],
    taskId: taskIdMatch?.[1]
  };
}

// For testing
export async function clearLatestReport(): Promise<void> {
  try {
    await unlink(LATEST_REPORT);
    console.log('clearLatestReport: unlink succeeded');
  } catch (e) {
    // File might not exist - ignore
    console.log('clearLatestReport error (ignored):', e);
  }
  // Verify
  if (existsSync(LATEST_REPORT)) {
    console.log('WARNING: File still exists after unlink!');
  }
}
